const escapeRegex = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const termsByLength = Object.keys(MEDICAL_GLOSSARY).sort((a, b) => b.length - a.length);
// Word-ending terms must be complete words; SI- and ST- can also prefix a
// pattern name (e.g. SI-LPDs), so they do not need a trailing word boundary.
const glossaryPattern = new RegExp(
  `\\b(${termsByLength.map((term) => `${escapeRegex(term)}${/[a-z0-9_]$/i.test(term) ? "(?![a-z0-9_])" : ""}`).join("|")})`,
  "gi",
);

/**
 * Split text into plain and glossary segments. Longest terms are matched first,
 * so "homonymous hemianopia" is treated as one term rather than "hemianopia".
 */
export function tokenizeMedicalText(text) {
  if (typeof text !== "string" || !text) return [{ text: text ?? "" }];

  const parts = [];
  let cursor = 0;
  for (const match of text.matchAll(glossaryPattern)) {
    if (match.index > cursor) parts.push({ text: text.slice(cursor, match.index) });
    const displayed = match[0];
    const canonical = termsByLength.find((term) => term.toLowerCase() === displayed.toLowerCase());
    parts.push({ text: displayed, term: canonical, definition: MEDICAL_GLOSSARY[canonical] });
    cursor = match.index + displayed.length;
  }
  if (cursor < text.length) parts.push({ text: text.slice(cursor) });
  return parts.length ? parts : [{ text }];
}
